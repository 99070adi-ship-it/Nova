/**
 * Lesson content for every step of the onboarding journey. The SEQUENCE is not defined here: the
 * backend owns the step keys, order, titles and completion rules
 * (backend/app/services/onboarding_service.py's `STEP_DEFINITIONS`, mirrored in
 * `contracts/onboarding-steps.json`), and the Guide reads the count and current step from
 * `/onboarding/progress`. This file only supplies what NOVA demonstrates for each server step —
 * `lib/novaLessons.test.ts` fails if a server step has no lesson or a title drifts. Steps already
 * satisfied by seeded data (e.g. `collections` in a demo workspace) simply show as done in the
 * progress and their lesson never runs. Every value below is real VELORA brand/catalog text,
 * matching backend/app/services/demo_service.py, so the demonstration always reads as NOVA
 * working on this store, never a generic placeholder.
 */
export interface LessonStep {
  key: string;
  /** Mirrors backend/app/services/onboarding_service.py's _STEP_TITLES exactly — shown
   * immediately as the Guide's stated objective (requirement 1) before any narration call has
   * even resolved, so there's never a silent/unexplained moment. */
  title: string;
  /** The route this step's real UI lives on — the widget navigates here first if the visitor
   * isn't already on it, so the whole ten-step tour reads as one continuous flow regardless of
   * which page a step's real action happens to live on. */
  path: string;
  demoActions: UIAction[];
  /** NOVA's narration for this step, written to be typed out slowly (2 characters per second, see
   * lib/typewriter.ts): short on purpose. `intro` is shown in the centered presentation that opens
   * every step, `explain` after the demonstration, `done` when the step is verified complete. They are
   * authored here, not generated by a model, so the length is guaranteed and the tour never waits on
   * a network call before NOVA starts speaking. lib/novaLessons.test.ts enforces the length budget. */
  intro: string;
  explain: string;
  done: string;
  /** Lessons with two real actions only: what NOVA says (centered, typed) right after the visitor's
   * FIRST action succeeds and before the second control is highlighted. */
  respond?: string;
  /** The EXACT label of the real control the user needs to press to perform this step's action —
   * authored here as plain data, not left to whatever an LLM's narration happens to mention, so
   * "click X" is always correct even against a real (non-fake) provider. useNovaLesson's
   * `userTurnTarget` is derived from this same lesson's own last demoAction with a target, since
   * NOVA's demo always ends by spotlighting the exact control the user then needs to press. */
  nextActionLabel: string;
  /** For a lesson needing a second real action after the first succeeds (nl_edit: propose, then
   * apply; run_business: check health, then fix) — the target NOVA spotlights once the first
   * action's result makes it exist, and its exact button label. */
  secondUserTurnTarget?: string;
  secondActionLabel?: string;
  /** One concise sentence on what happens once this step is actually done — shown alongside the
   * step's own completion message so the user always knows what's coming next, not just that
   * this one thing finished. */
  afterActionHint: string;
  /** The lesson's one playful line (see lib/novaScript.ts). */
  quip: string;
}

