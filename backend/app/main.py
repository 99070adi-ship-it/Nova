from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from fastapi.staticfiles import StaticFiles
import pathlib

from contextlib import asynccontextmanager

from app.ai.speech import KokoroSpeechProvider, get_speech_provider, peek_speech_status
from app.api.v1 import api_router
from app.config import get_settings
from app.errors import register_error_handlers

settings = get_settings()

@asynccontextmanager
async def lifespan(_app: FastAPI):
    # Refuse to start a non-local deployment that is still signing tokens with the public development secret.
    if settings.env != "local" and (settings.jwt_secret.startswith("dev-secret") or len(settings.jwt_secret) < 32):
        raise RuntimeError("JWT_SECRET must be set to a unique random value (32+ characters) when ENV is not 'local'.")
    # Optional: load the voice model at startup (TTS_PRELOAD=true) so the first narration is not slow.
    # Never fatal: if it cannot load, the status says so and everything else keeps working.
    if settings.tts_preload and settings.tts_provider == "kokoro":
        provider = get_speech_provider()
        if isinstance(provider, KokoroSpeechProvider):
            provider.engine.start_loading()
    yield


app = FastAPI(title="NOVA API", lifespan=lifespan)
register_error_handlers(app)

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(api_router, prefix="/api/v1")

# Public, cacheable assets: VELORA's illustrations (generated by scripts/generate_velora_assets.py). Read-only.
_STATIC = pathlib.Path(__file__).parent / "static"
_STATIC.mkdir(exist_ok=True)
app.mount("/static", StaticFiles(directory=_STATIC), name="static")


@app.get("/healthz")
async def healthz() -> dict:
    return {"status": "ok"}


@app.get("/readyz")
async def readyz() -> dict:
    # The app is ready regardless of the voice engine (voice is optional); its state is reported for
    # operators. Reading it never loads the model.
    voice = peek_speech_status()
    from app.ai import status as ai_status

    ai = ai_status.describe()
    # AI readiness is informational like voice: the app serves everything else without it.
    return {
        "status": "ready", "voice": {"engine": settings.tts_provider, "state": voice["state"]},
        "ai": {k: ai.get(k) for k in ("provider", "model", "mode", "real_ai", "credentials_configured", "ready")},
    }

